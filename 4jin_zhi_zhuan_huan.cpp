#include<stdio.h>
int main()
{
	int a=45,b=045,c=0x45;
	float d=12.,e=.344,f=.37e3;
	printf("a=%d,b=%d,c=%d\n",a,b,c);
	printf("a=%d,b=%o,c=%x\n",a,b,c);
	printf("d=%f,e=%f,f=%f\n",d,e,f);
	return 0;
	
}
/* 
【文字解读】
1. 第一行输出 a=45,b=37,c=69：
   a赋十进制45；b以0开头是八进制045，转为十进制是37；c以0x开头是十六进制0x45，转为十进制是69。

2. 第二行输出 a=45,b=45,c=45：
   %o输出八进制，%x输出十六进制。b原本是八进制045，输出45；c原本是十六进制0x45，输出45。

3. 第三行输出 d=12.000000,e=0.344000,f=370.000000：
   d=12. 即12.0；e=.344 即0.344；f=.37e3 是科学计数法，等于0.37*10^3即370。%f默认输出6位小数。
*/

